function _ring_recurrence_geometry(k,rho,z,rho2,z2,normal,projection)
    all(isfinite,(k,rho,z,rho2,z2,normal,projection)) || return nothing
    rho>0 && rho2>0 || return nothing
    product=rho*rho2
    isfinite(product) && product>=floatmin(Float64) || return nothing
    distance=hypot(rho-rho2,z-z2)
    isfinite(distance) && distance>=_RING_DISTANCE_FLOOR || return nothing
    distance<=0.5sqrt(product) && 0<abs(k)*sqrt(product)<=160 || return nothing
    B=2product
    A=distance^2+B
    R=sqrt(A)
    all(isfinite,(A,B,R)) || return nothing
    (;k=abs(k),rho,normal,projection,distance,A,B,R,alpha=B/A,kappa=abs(k)*R,
        bm=distance/sqrt(B),bp=sqrt((A+B)/B),conjugate=k<0)
end

@inline function _ring_recurrence_contour_intersection(beta,sign,ae,be)
    coefficient=2sign+4ae^2*beta^2/be^2
    power4=2be^2/(coefficient+hypot(coefficient,2be))
    tau=sqrt(sqrt(power4))
    theta=atan(2beta*sqrt(power4)/be,(sign+power4)/ae)
    (;tau,theta)
end

# Select quadrature tables using beta/tau_end^2 after interval rescaling.
function _ring_recurrence_table_index(beta,tau_end)
    scaled=beta/tau_end^2
    isfinite(scaled) && scaled>0 || return -1
    scaled>1 && return 0
    for j in 1:10
        scaled>=ldexp(1.0,-5j) && return j
    end
    -1
end

@inline function _ring_recurrence_chebyshev_pair(z,delta,plus,m)
    m==1 && return (one(z),z)
    # The separate endpoint factors preserve small distances from +/-1.
    root=sqrt(-delta)*sqrt(plus)
    w=z+root
    abs(w)<1 && (w=inv(w))
    power=w^m
    reciprocal=inv(power)
    ((power/w+w*reciprocal)/2,(power+reciprocal)/2)
end

@inline function _ring_recurrence_seed_add!(output,g,base,s,delta,p0,p1,weight)
    derivative=(im*g.kappa/s-inv(s*s))/(2g.A)
    common=base*(weight/(4pi^2*g.R))
    v0,v1=common*p0,common*p1
    a0,a1=v0*derivative,v1*derivative
    @inbounds begin
        output[1,1]+=v0
        output[2,1]+=v1
        output[1,2]+=a0
        output[2,2]+=a1
        output[1,3]+=a0*delta
        output[2,3]+=a1*delta
    end
    nothing
end

function _ring_recurrence_gamma1!(output,g,m,tau_left,tau_right,rule,unit_interval)
    nodes,weights=rule
    root_alpha=sqrt(g.alpha)
    phase=cis(g.kappa*root_alpha*g.bm)
    width=tau_right-tau_left
    @inbounds for j in eachindex(nodes)
        tau=unit_interval ? tau_left+width*nodes[j] : tau_left+width*(nodes[j]+1)/2
        weight=unit_interval ? width*weights[j] : width*weights[j]/2
        t2=tau*tau
        q=t2-2im*g.bm
        delta=-t2*q
        plus=2-delta
        z=1-delta
        s=root_alpha*(g.bm+im*t2)
        base=-4/root_alpha*exp(-g.kappa*root_alpha*t2)*phase/(sqrt(q)*sqrt(plus))
        p0,p1=_ring_recurrence_chebyshev_pair(z,delta,plus,m)
        _ring_recurrence_seed_add!(output,g,base,s,delta,p0,p1,-weight)
    end
    length(nodes)
end

function _ring_recurrence_gamma2!(output,g,m,tau_end,rule)
    nodes,weights=rule
    root_alpha=sqrt(g.alpha)
    phase=cis(g.kappa*root_alpha*g.bp)
    @inbounds for j in eachindex(nodes)
        tau=tau_end*(nodes[j]+1)/2
        t2=tau*tau
        plus=t2*(t2-2im*g.bp)
        delta=2-plus
        z=-1+plus
        s=root_alpha*(g.bp+im*t2)
        base=-4im/root_alpha*exp(-g.kappa*root_alpha*t2)*phase/
            (sqrt(t2-2im*g.bp)*sqrt(delta))
        p0,p1=_ring_recurrence_chebyshev_pair(z,delta,plus,m)
        _ring_recurrence_seed_add!(output,g,base,s,delta,p0,p1,tau_end*weights[j]/2)
    end
    length(nodes)
end

function _ring_recurrence_ellipse!(output,g,m,eta,ae,be,theta_left,theta_right,rule)
    nodes,weights=rule
    width=theta_right-theta_left
    shalf=sinh(eta/2)^2
    cm0,sm0=cosh((m-1)*eta),sinh((m-1)*eta)
    cm1,sm1=cosh(m*eta),sinh(m*eta)
    @inbounds for j in eachindex(nodes)
        theta=theta_left+width*(nodes[j]+1)/2
        sn,cs=sincos(theta)
        delta=2sin(theta/2)^2-2shalf*cs+im*be*sn
        plus=2cos(theta/2)^2+2shalf*cs-im*be*sn
        s=sqrt(g.alpha*(g.bm^2+delta))
        base=exp(im*g.kappa*s)/(s*sqrt(delta)*sqrt(plus))*(-ae*sn-im*be*cs)
        if m==1
            p0,p1=1.0+0im,1-delta
        else
            sn0,cs0=sincos((m-1)*theta)
            sn1,cs1=sincos(m*theta)
            p0,p1=complex(cs0*cm0,-sn0*sm0),complex(cs1*cm1,-sn1*sm1)
        end
        _ring_recurrence_seed_add!(output,g,base,s,delta,p0,p1,-width*weights[j]/2)
    end
    length(nodes)
end

function _ring_recurrence_seed!(output,g,m,refined,workspace)
    fill!(output,0)
    contour_mode=max(m,5)
    eta=log(100.0)/contour_mode
    ae,be=cosh(eta),sinh(eta)
    left=_ring_recurrence_contour_intersection(g.bm,1,ae,be)
    right=_ring_recurrence_contour_intersection(g.bp,-1,ae,be)
    all(isfinite,(left.tau,left.theta,right.tau,right.theta)) && left.tau>0 && right.tau>0 || return false
    index=_ring_recurrence_table_index(g.bm,left.tau)
    # Extreme table families remain excluded after independent moment checks.
    0<=index<=10 || return false
    smooth=refined ? workspace.gauss64 : workspace.gauss32
    evaluations=0
    if refined && index>0
        half=left.tau/2
        halfindex=_ring_recurrence_table_index(g.bm,half)
        halfindex<0 && return false
        near=halfindex==0 ? smooth : _RING_RECURRENCE_TABLES[halfindex]
        evaluations+=_ring_recurrence_gamma1!(output,g,m,0.0,half,near,halfindex>0)
        evaluations+=_ring_recurrence_gamma1!(output,g,m,half,left.tau,smooth,false)
    else
        near=index==0 ? smooth : _RING_RECURRENCE_TABLES[index]
        evaluations+=_ring_recurrence_gamma1!(output,g,m,0.0,left.tau,near,index>0)
    end
    evaluations+=_ring_recurrence_gamma2!(output,g,m,right.tau,smooth)
    ellipse=m==1 ? (refined ? workspace.lowellipsefine : workspace.lowellipse) :
        (refined ? workspace.highellipsefine : workspace.highellipse)
    evaluations+=_ring_recurrence_ellipse!(output,g,m,eta,ae,be,left.theta,right.theta,ellipse)
    workspace.seed_evaluations+=evaluations
    all(isfinite,output)
end

function _ring_recurrence_seed_check(g,fine,coarse)
    @inbounds for component in 1:3, j in 1:2
        scale=component==1 ? g.R : component==2 ? g.R*g.distance^2 : g.R*g.A
        a,b=fine[j,component]*scale,coarse[j,component]*scale
        abs(a-b)<=2e-13+2e-11abs(a) || return false
    end
    true
end

function _ring_recurrence_band_residual(workspace,answer,forcing,maximum_mode=workspace.N-2)
    largest=0.0
    @inbounds for m in 2:min(workspace.N-2,maximum_mode)
        i=m-1
        f=forcing===nothing ? 0.0im : forcing[m+1]/workspace.scales[i]
        residual=-f
        magnitude=abs(f)
        for offset in -2:2
            value=workspace.coefficients[offset+3,i]*answer[m+offset+1]
            residual+=value
            magnitude+=abs(value)
        end
        largest=max(largest,abs(residual)/max(magnitude,floatmin(Float64)))
    end
    workspace.last_residual=max(workspace.last_residual,largest)
    isfinite(largest) && largest<=5e-12
end

# Reuse pivots for the band LU with two lower and four filled upper diagonals.
function _ring_recurrence_lu_factor!(band,pivots,n::Int,
        start::Int=1,last_column::Int=1,checkpoint=nothing)::Bool
    checkpoint===nothing || (checkpoint.n=0)
    @inbounds for j in start:n
        if checkpoint!==nothing && j==max(1,n-3)
            checkpoint.last_column=last_column
            for column in j:n, row in 1:7
                checkpoint.band[row,column-j+1]=band[row,column]
            end
        end
        if j+4<=n
            band[1,j+4]=0.0
            band[2,j+4]=0.0
        end
        lower=min(2,n-j)
        pivot_offset=0
        largest=abs(band[5,j])
        for offset in 1:lower
            candidate=abs(band[5+offset,j])
            isfinite(candidate) || return false
            if candidate>largest
                largest=candidate
                pivot_offset=offset
            end
        end
        isfinite(largest) && largest>0 || return false
        pivots[j]=j+pivot_offset
        last_column=max(last_column,min(n,j+2+pivot_offset))
        if pivot_offset!=0
            for column in j:last_column
                first=5+j-column
                second=first+pivot_offset
                band[first,column],band[second,column]=band[second,column],band[first,column]
            end
        end
        inverse=inv(band[5,j])
        isfinite(inverse) || return false
        for offset in 1:lower
            band[5+offset,j]*=inverse
        end
        for column in j+1:last_column
            first=5+j-column
            upper=band[first,column]
            for offset in 1:lower
                band[first+offset,column]-=band[5+offset,j]*upper
            end
        end
    end
    checkpoint===nothing || (checkpoint.n=n)
    true
end
function _ring_recurrence_lu_solve!(band,pivots,rhs,n::Int)::Bool
    @inbounds for j in 1:n-1
        pivot=pivots[j]
        for component in 1:2
            if pivot!=j
                rhs[j,component],rhs[pivot,component]=rhs[pivot,component],rhs[j,component]
            end
            value=rhs[j,component]
            for offset in 1:min(2,n-j)
                rhs[j+offset,component]-=band[5+offset,j]*value
            end
        end
    end
    @inbounds for component in 1:2
        for row in n:-1:1
            value=rhs[row,component]
            for column in row+1:min(n,row+4)
                value-=band[5+row-column,column]*rhs[column,component]
            end
            rhs[row,component]=value/band[5,row]
        end
    end
    true
end

function _ring_recurrence_factor!(workspace,g,N)
    5<=N<=workspace.capacity || return false
    workspace.N=N
    n=N-3
    band=workspace.band
    @inbounds for j in 1:n, i in 1:7
        band[i,j]=0
    end
    phase=g.alpha^2*g.kappa^2
    @inbounds for m in 2:N-2
        c=(phase/(16m*(m-1)),-g.alpha*(2m-1)/(4m),
            1-phase/(8*(m^2-1)),-g.alpha*(2m+1)/(4m),phase/(16m*(m+1)))
        scale=maximum(abs,c)
        i=m-1
        workspace.scales[i]=scale
        for offset in -2:2
            value=c[offset+3]/scale
            workspace.coefficients[offset+3,i]=value
            j=m+offset-1
            1<=j<=n && (band[5+i-j,j]=value)
        end
    end
    _ring_recurrence_lu_factor!(band,workspace.pivots,n,1,1,workspace.checkpoint)
end

# Restore four checkpoint columns before extending the same-geometry recurrence.
function _ring_recurrence_extend!(workspace,g,N)
    oldn=workspace.N-3
    checkpoint=workspace.checkpoint
    2<=oldn==checkpoint.n && workspace.N<N<=workspace.capacity || return false
    n=N-3
    start=max(1,oldn-3)
    band=workspace.band
    @inbounds for column in start:oldn, row in 1:7
        band[row,column]=checkpoint.band[row,column-start+1]
    end
    @inbounds for column in oldn+1:n, row in 1:7
        band[row,column]=0
    end
    phase=g.alpha^2*g.kappa^2
    @inbounds for m in max(2,oldn):N-2
        c=(phase/(16m*(m-1)),-g.alpha*(2m-1)/(4m),
            1-phase/(8*(m^2-1)),-g.alpha*(2m+1)/(4m),phase/(16m*(m+1)))
        scale=maximum(abs,c)
        i=m-1
        workspace.scales[i]=scale
        for offset in -2:2
            value=c[offset+3]/scale
            workspace.coefficients[offset+3,i]=value
            j=m+offset-1
            if 1<=j<=n && (i>oldn || j>oldn)
                band[5+i-j,j]=value
            end
        end
    end
    workspace.N=N
    _ring_recurrence_lu_factor!(band,workspace.pivots,n,start,
        checkpoint.last_column,checkpoint)
end

function _ring_recurrence_solve!(answer,workspace,boundaries,forcing=nothing)
    N=workspace.N
    n=N-3
    rhs=workspace.rhs
    @inbounds begin
        answer[1]=boundaries[1]
        answer[2]=boundaries[2]
        answer[N]=boundaries[3]
        answer[N+1]=boundaries[4]
        answer[N+2]=0
        for m in 2:N-2
            i=m-1
            value=forcing===nothing ? 0.0im : forcing[m+1]/workspace.scales[i]
            for offset in -2:2
                j=m+offset
                (j<2 || j>N-2) && (value-=workspace.coefficients[offset+3,i]*answer[j+1])
            end
            rhs[i,1]=real(value)
            rhs[i,2]=imag(value)
        end
        _ring_recurrence_lu_solve!(workspace.band,workspace.pivots,rhs,n) || return false
        for j in 1:n
            answer[j+2]=complex(rhs[j,1],rhs[j,2])
        end
    end
    _ring_recurrence_band_residual(workspace,answer,forcing)
end

function _ring_recurrence_nondecay!(workspace,g,low,high)
    N=workspace.N
    G,A,H=workspace.G,workspace.A,workspace.H
    _ring_recurrence_solve!(G,workspace,(low[1,1],low[2,1],high[1,1],high[2,1])) || return false
    # Store derivative forcing in H while preserving the G coefficients.
    @inbounds for j in 1:N+1
        H[j]=-G[j]/g.A
    end
    _ring_recurrence_solve!(A,workspace,(low[1,2],low[2,2],high[1,2],high[2,2]),H) || return false
    @inbounds begin
        H[N]=high[1,3]
        H[N+1]=high[2,3]
        H[N+2]=0
        for m in N-1:-1:1
            H[m]=H[m+2]-(-(m+1)*G[m+2]+2m*G[m+1]-(m-1)*G[m])/g.B
        end
    end
    _ring_recurrence_low_check(workspace,g,low)
end

function _ring_recurrence_decay!(workspace,g,low)
    N=workspace.N
    G,A,H=workspace.G,workspace.A,workspace.H
    _ring_recurrence_solve!(G,workspace,(low[1,1],low[2,1],0.0im,0.0im)) || return false
    @inbounds begin
        A[N+1]=A[N+2]=0
        H[N+1]=H[N+2]=0
        for m in N:-1:1
            A[m]=A[m+2]-2m*G[m+1]/g.B
            H[m]=H[m+2]-(-(m+1)*G[m+2]+2m*G[m+1]-(m-1)*G[m])/g.B
        end
    end
    true
end

function _ring_recurrence_decay_residual(workspace,g)
    N=workspace.N
    G,A=workspace.G,workspace.A
    # Check requested-mode derivative residuals before validating the remote boundary by extension.
    @inbounds for m in 2:min(last(workspace.modes),N-2)
        i=m-1
        forcing=-G[m+1]/(g.A*workspace.scales[i])
        residual=-forcing
        magnitude=abs(forcing)
        for offset in -2:2
            value=workspace.coefficients[offset+3,i]*A[m+offset+1]
            residual+=value
            magnitude+=abs(value)
        end
        ratio=abs(residual)/max(magnitude,floatmin(Float64))
        workspace.last_residual=max(workspace.last_residual,ratio)
        isfinite(ratio) && ratio<=5e-12 || return false
    end
    true
end

function _ring_recurrence_low_check(workspace,g,low)
    @inbounds for j in 1:2
        for (value,reference,scale) in ((workspace.A[j],low[j,2],g.R*g.distance^2),
                                      (workspace.H[j],low[j,3],g.R*g.A))
            a,b=value*scale,reference*scale
            abs(a-b)<=1e-12+1e-10abs(b) || return false
        end
    end
    true
end

function _ring_recurrence_output!(output,workspace,g)
    count=length(workspace.modes)
    width=workspace.width
    @inbounds for j in 1:width
        if j<=count
            index=workspace.modes[j]+1
            K=4pi*(g.normal*g.rho*workspace.H[index]-g.projection*workspace.A[index])
            V=2pi*workspace.G[index]
            output[j]=g.conjugate ? conj(K) : K
            output[width+j]=g.conjugate ? conj(V) : V
        else
            output[j]=output[width+j]=0
        end
    end
    all(isfinite,output)
end

function _ring_recurrence_output_check(workspace,rtol)
    @inbounds for j in eachindex(workspace.answer)
        workspace.difference[j]=workspace.answer[j]-workspace.coarse[j]
    end
    difference=norm(workspace.difference)
    target=max(_QUAD_ATOL,rtol*norm(workspace.answer))
    isfinite(difference) && isfinite(target) && difference<=0.05target
end

@noinline function _ring_recurrence_direct!(workspace,g,rtol,M)::Int
    _ring_recurrence_seed!(workspace.high,g,M,true,workspace) &&
        _ring_recurrence_seed!(workspace.highcheck,g,M,false,workspace) &&
        _ring_recurrence_seed_check(g,workspace.high,workspace.highcheck) || return 4
    _ring_recurrence_factor!(workspace,g,M) || return 5
    _ring_recurrence_nondecay!(workspace,g,workspace.low,workspace.high) || return 5
    _ring_recurrence_output!(workspace.answer,workspace,g) || return 8
    _ring_recurrence_nondecay!(workspace,g,workspace.lowcheck,workspace.highcheck) || return 5
    _ring_recurrence_output!(workspace.coarse,workspace,g) || return 8
    _ring_recurrence_output_check(workspace,rtol) || return 7
    return 0
end

@noinline function _ring_recurrence_checked_decay!(workspace,g,rtol,N)::Int
    workspace.extensions=0
    workspace.last_residual=0
    N<=workspace.capacity || return 6
    _ring_recurrence_factor!(workspace,g,N) && _ring_recurrence_decay!(workspace,g,workspace.low) || return 5
    _ring_recurrence_output!(workspace.previous,workspace,g) || return 8
    consecutive=0
    for extension in 1:12
        N=cld(5N,4)
        N<=workspace.capacity || return 6
        workspace.extensions=extension
        workspace.last_residual=0
        _ring_recurrence_extend!(workspace,g,N) && _ring_recurrence_decay!(workspace,g,workspace.low) || return 5
        _ring_recurrence_output!(workspace.answer,workspace,g) || return 8
        stable=true
        @inbounds for j in eachindex(workspace.answer)
            stable &= abs(workspace.answer[j]-workspace.previous[j])<=1e-13+1e-10abs(workspace.answer[j])
        end
        stable &= _ring_recurrence_low_check(workspace,g,workspace.low)
        stable &= _ring_recurrence_decay_residual(workspace,g)
        consecutive=stable ? consecutive+1 : 0
        if consecutive==2
            _ring_recurrence_decay!(workspace,g,workspace.lowcheck) &&
                _ring_recurrence_decay_residual(workspace,g) || return 5
            _ring_recurrence_output!(workspace.coarse,workspace,g) || return 8
            _ring_recurrence_output_check(workspace,rtol) || return 7
            return 0
        end
        copyto!(workspace.previous,workspace.answer)
    end
    6
end

function _ring_recurrence_candidate!(workspace,g,rtol)
    workspace.seed_evaluations=0
    workspace.extensions=0
    workspace.last_residual=0
    _ring_recurrence_seed!(workspace.low,g,1,true,workspace) &&
        _ring_recurrence_seed!(workspace.lowcheck,g,1,false,workspace) &&
        _ring_recurrence_seed_check(g,workspace.low,workspace.lowcheck) || return 4
    M=last(workspace.modes)
    transition=g.kappa*g.alpha/sqrt(2*(1+sqrt((1-g.alpha)*(1+g.alpha))))
    geometric_decay=2asinh(g.bm/sqrt(2))
    nondecay=M<=transition || M*geometric_decay<=16 || (g.bm^2<=1e-5 && M<=3000)
    stop=transition+36/geometric_decay
    if !nondecay
        return _ring_recurrence_checked_decay!(workspace,g,rtol,max(M+16,ceil(Int,stop)))
    end
    # Preserve the existing work bound and space for two rounded extensions.
    work_limit=64workspace.width
    if workspace.width in (16,32) && length(workspace.modes)>=8 &&
        first(workspace.modes)>=256
        work_limit=max(work_limit,12M)
    end
    limit=min(work_limit,fld(4fld(4workspace.capacity,5),5))
    admitted=isfinite(stop) && stop<=limit && M+16<=limit
    # Try affordable checked decay before high-mode seeds, retaining direct recovery after failure.
    preferred=admitted && workspace.width in (16,32,64,128) &&
        length(workspace.modes)>=8 && first(workspace.modes)>=128 &&
        stop<=12M && M+16<=12M
    decay_reason=0
    if preferred
        decay_reason=_ring_recurrence_checked_decay!(workspace,g,rtol,max(M+16,ceil(Int,stop)))
        decay_reason==0 && return 0
    end
    workspace.extensions=0
    workspace.last_residual=0
    direct_reason=_ring_recurrence_direct!(workspace,g,rtol,M)
    direct_reason==0 && return 0
    direct_reason in (4,5,7) || return direct_reason
    admitted || return direct_reason
    preferred && return decay_reason
    _ring_recurrence_checked_decay!(workspace,g,rtol,max(M+16,ceil(Int,stop)))
end

@noinline function _ring_recurrence_KV(k,rho,z,rho2,z2,normal,projection,modes,rtol,::Val{N},::Nothing) where {N}
    false,zero(SVector{2N,ComplexF64})
end
@noinline function _ring_recurrence_KV(k,rho,z,rho2,z2,normal,projection,modes,rtol,::Val{N},workspace) where {N}
    rejected=(false,zero(SVector{2N,ComplexF64}))
    workspace.width==N && workspace.modes==modes && isfinite(rtol) && rtol>=1e-7 || return rejected
    g=_ring_recurrence_geometry(k,rho,z,rho2,z2,normal,projection)
    if g===nothing
        workspace.last_reason=:geometry
        return rejected
    end
    reason=try
        _ring_recurrence_candidate!(workspace,g,rtol)
    catch err
        if err isa LinearAlgebra.SingularException || err isa LinearAlgebra.LAPACKException
            5
        else
            rethrow()
        end
    end
    if reason!=0
        workspace.last_reason=(:unused,:unused,:geometry,:seed,:band,:tail,:quadrature,:nonfinite)[reason]
        return rejected
    end
    workspace.last_reason=:accepted
    true,SVector{2N,ComplexF64}(workspace.answer)
end

# Bound Fourier tails by analytic continuation with a floating-point inflation allowance.
function _ring_fourier_tail_logbound(k,rho,z,rho2,z2,normal,projection,modes)
    isempty(modes) && return Inf
    0<=first(modes)<=last(modes)<=512 || return Inf
    all(isfinite,(k,rho,z,rho2,z2,normal,projection)) || return Inf
    rho>0 && rho2>0 && floatmin(Float64)<=rho*rho2<Inf || return Inf
    radius=sqrt(rho*rho2);distance=hypot(rho-rho2,z-z2)
    distance>=_RING_DISTANCE_FLOOR || return Inf
    distance_squared=distance*distance
    isfinite(distance_squared) && distance_squared>=floatmin(Float64) || return Inf
    eta=2asinh(distance/(2radius))
    isfinite(eta) && eta>0 || return Inf
    y=min(1.5,.9eta)
    isfinite(y) && 0<y<eta || return Inf
    imaginary_radius=2radius*sinh(y/2)
    isfinite(imaginary_radius) && imaginary_radius<distance || return Inf
    phase=abs(k)*radius*exp(-eta/2)*sinh(y)
    log_rmin=log(distance)+log1p(-(imaginary_radius/distance)^2)/2
    rmax=hypot(distance,2radius*cosh(y/2))
    beta=normal/(2rho2)
    isfinite(beta) && (normal==0 || abs(beta)>=floatmin(Float64)) || return Inf
    beta_distance=beta*distance_squared
    isfinite(beta_distance) && (beta==0 || abs(beta_distance)>=floatmin(Float64)) || return Inf
    alpha_bound=abs(muladd(beta,distance^2,projection))+32eps(Float64)*(abs(projection)+abs(beta_distance))
    beta_bound=abs(beta)*(1+8eps(Float64))
    log_alpha=alpha_bound==0 ? -Inf : log(alpha_bound)-3log_rmin
    log_beta=beta_bound==0 ? -Inf : log(beta_bound)-log_rmin
    largest=max(log_alpha,log_beta)
    log_projection_bound=largest==-Inf ? -Inf :
        largest+log1p(exp(min(log_alpha,log_beta)-largest))
    log_kr=k==0 ? -Inf : log(abs(k))+log(rmax)
    log_derivative=max(log_kr,0.)+log1p(exp(-abs(log_kr)))
    logK=log_derivative+log_projection_bound
    logV=-log_rmin
    log_norm=max(logK,logV)+log1p(exp(-2abs(logK-logV)))/2-log(2.)
    rounding=512eps(Float64)*(1+phase+last(modes)*y+abs(logV)+(isfinite(logK) ? abs(logK) : 0))
    logB=phase+log_norm+rounding
    log_series=(log(-expm1(-2length(modes)*y))-log(-expm1(-2y)))/2
    return logB-first(modes)*y+log_series
end
